#!/usr/bin/env python3
"""Write the website's candidate-window palettes from the design tokens.

Each candidate style gets one block per tone:
  [data-cand-style="flow"][data-cand-tone="light"] { --cand-...: ...; }
Alpha values (0-255 in the tokens) become --cand-<name> fractions.

Usage:
  python site/scripts/candidate_tokens.py           # writes site/assets/css/candidate-tokens.css
  python site/scripts/candidate_tokens.py --check   # fails when the file is out of date
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
TOKENS = ROOT / "assets" / "branding" / "theme" / "design_tokens.json"
OUTPUT = ROOT / "site" / "assets" / "css" / "candidate-tokens.css"


def render(tokens: dict) -> str:
    lines = ["/* Generated by site/scripts/candidate_tokens.py from",
             "   assets/branding/theme/design_tokens.json. Do not edit. */", ":root {"]
    lines += [f"  --brand-{name}: {value};" for name, value in tokens["brand"].items()]
    lines += ["}", ""]
    for style, tones in tokens["candidate"].items():
        for tone in ("light", "dark"):
            lines.append(f'[data-cand-style="{style}"][data-cand-tone="{tone}"] {{')
            for name, value in tones[tone].items():
                if isinstance(value, int):
                    lines.append(f"  --cand-{name}: {value / 255:.3f};")
                else:
                    lines.append(f"  --cand-{name}: {value};")
            lines += ["}", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the output is out of date")
    args = parser.parse_args()
    css = render(json.loads(TOKENS.read_text(encoding="utf-8")))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != css:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date; run site/scripts/candidate_tokens.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(css, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
