def read_existing() -> tuple[set[tuple[str, str]], set[str]]:
    keys: set[tuple[str, str]] = set()
    words: set[str] = set()
    for name in ("core_zh_pinyin.tsv", "local_core_zh_pinyin.tsv"):
        for line in (SOURCE_ROOT / "resources" / "dictionary" / name).read_text(encoding="utf-8-sig").splitlines():
            if not line or line.startswith("#"):
                continue
            fields = line.split("\t")
            if len(fields) == 3:
                keys.add((fields[0], fields[1]))
                words.add(fields[1])
    return keys, words

def author_entries(batch: str):
    selected = SECTIONS[:10] if batch == "001" else SECTIONS[10:]
    for category, frequency, content in selected:
        for word in content.split():
            if word not in EXCLUDED:
                yield category, FREQUENCY_OVERRIDES.get(word, frequency), word

def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--coverage-only", action="store_true")
    parser.add_argument("--batch", choices=("001", "002"), default="001")
    args = parser.parse_args()
    existing_keys, existing_words = read_existing()
    if args.batch == "002":
        for line in (OUTPUT_DIR / "lexicon_batch_001.tsv").read_text(encoding="utf-8").splitlines():
            if line and not line.startswith("#"):
                pinyin, word, _ = line.split("\t")
                existing_keys.add((pinyin, word))
                existing_words.add(word)
    authored = list(author_entries(args.batch))
    if args.coverage_only:
        missing = sorted({word for _, _, word in authored if word not in existing_words})
        print(json.dumps({"authored": len(authored), "missing_words": len(missing), "sample": missing[:40]}, ensure_ascii=False))
        return
    from pypinyin import Style, lazy_pinyin
    candidates: dict[tuple[str, str], tuple[str, int]] = {}
    for category, frequency, word in authored:
        pinyin = OVERRIDES.get(word) or "".join(lazy_pinyin(word, style=Style.NORMAL, strict=True))
        if not pinyin or not pinyin.isascii() or not pinyin.isalpha() or pinyin != pinyin.lower():
            raise ValueError(f"Invalid pronunciation: {word!r} -> {pinyin!r}")
        key = (pinyin, word)
        if key in existing_keys:
            continue
        old = candidates.get(key)
        if old is None or frequency > old[1]:
            candidates[key] = category, frequency
    rows = sorted(candidates.items(), key=lambda item: (item[1][0], item[0][0], item[0][1]))
    lines = []
    previous = None
    for (pinyin, word), (category, frequency) in rows:
        if category != previous:
            lines.append(f"# category: {category}")
            previous = category
        lines.append(f"{pinyin}\t{word}\t{frequency}")
    output = OUTPUT_DIR / f"lexicon_batch_{args.batch}.tsv"
    output.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    report = {
        "batch": f"lexicon_batch_{args.batch}", "authoring_source": "first_party_authored",
        "pronunciation_tool": "pypinyin authoring-only; explicit reviewed overrides",
        "external_lexicon_import": False, "authored_candidates": len(authored),
        "new_entries": len(rows), "category_counts": dict(Counter(category for _, (category, _) in rows)),
        "length_distribution": dict(sorted(Counter(len(word) for (_, word), _ in rows).items())),
        "sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
        "dedup_baseline_sha256": {
            name: hashlib.sha256((SOURCE_ROOT / "resources" / "dictionary" / name).read_bytes()).hexdigest()
            for name in ("core_zh_pinyin.tsv", "local_core_zh_pinyin.tsv")
        },
        "canonical_dictionaries_modified": False,
    }
    (OUTPUT_DIR / f"lexicon_batch_{args.batch}.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False))

if __name__ == "__main__":
    main()
