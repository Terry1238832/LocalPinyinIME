#!/usr/bin/env python3
"""Generate the design token outputs from assets/branding/theme/design_tokens.json.

  --header <file>  C++ header for the native surfaces (candidate window,
                   installer): solid colors as COLORREF, alpha values as int.
                   Each candidate style gets candidate_<style>_<mode>.
  --css <file>     CSS custom properties for the settings app.
  --check          with --css: fail when the file differs from what the tokens
                   produce, instead of writing it (run by ctest).

Usage:
  python tools/generate_design_tokens.py --css desktop/src/tokens.css
  python tools/generate_design_tokens.py --header build/generated/localpinyin_design_tokens.h
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "assets" / "branding" / "theme" / "design_tokens.json"
HEX = re.compile(r"^#[0-9A-Fa-f]{6}$")
# Outside a candidate-style scope, --cand-* is this style's palette.
DEFAULT_STYLE = "flow"


def identifier(name: str) -> str:
    return "k" + "".join(part[:1].upper() + part[1:] for part in re.split(r"[-_]", name))


def colorref(value: str) -> str:
    r, g, b = (int(value[i:i + 2], 16) for i in (1, 3, 5))
    return f"RGB(0x{r:02X}, 0x{g:02X}, 0x{b:02X})"


def header(tokens: dict) -> str:
    lines = ["#pragma once", "", "// Generated by tools/generate_design_tokens.py from",
             "// assets/branding/theme/design_tokens.json. Do not edit.", "",
             "#include <windows.h>", "", "namespace localpinyin::tokens {", ""]

    def block(namespace: str, values: dict) -> None:
        lines.append(f"namespace {namespace} {{")
        for key, value in values.items():
            if isinstance(value, int):
                lines.append(f"inline constexpr int {identifier(key)} = {value};")
            elif isinstance(value, str) and HEX.match(value):
                lines.append(f"inline constexpr COLORREF {identifier(key)} = {colorref(value)};")
        lines.append(f"}}  // namespace {namespace}")
        lines.append("")

    block("brand", tokens["brand"])
    for mode in ("light", "dark"):
        block(f"ui_{mode}", tokens["color"][mode])
    for style, modes in tokens["candidate"].items():
        for mode in ("light", "dark"):
            block(f"candidate_{style}_{mode}", modes[mode])
    lines += ["}  // namespace localpinyin::tokens", ""]
    return "\n".join(lines)


def css(tokens: dict) -> str:
    def candidate(style: str, mode: str) -> list[str]:
        return [f"  --cand-{key}: {value};" for key, value in tokens["candidate"][style][mode].items()
                if isinstance(value, str)]

    def declarations(mode: str) -> list[str]:
        result = [f"  --{key}: {value};" for key, value in tokens["color"][mode].items()]
        result += candidate(DEFAULT_STYLE, mode)
        result += [f"  --shadow-{key}: {value};" for key, value in tokens["shadow"][mode].items()]
        return result

    shared = [f"  --brand-{key}: {value};" for key, value in tokens["brand"].items()]
    shared += [f"  --radius-{key}: {value};" for key, value in tokens["radius"].items()]
    shared += [f"  --font-{key}: {value};" for key, value in tokens["font"].items()]
    shared += [f"  --size-{key}: {value};" for key, value in tokens["type"].items()]
    for key, value in tokens["motion"].items():
        shared.append(f"  --{'dur-' + key if not key.startswith('ease') else key}: {value};")
    # Fixed references to both themes, for previews that show a theme other
    # than the active one.
    for mode in ("light", "dark"):
        shared += [f"  --{mode}-{key}: {value};" for key, value in tokens["color"][mode].items()]
    lines = ["/* Generated by tools/generate_design_tokens.py from",
             "   assets/branding/theme/design_tokens.json. Do not edit. */",
             ":root {", "  color-scheme: light;", *shared, *declarations("light"), "}", "",
             ':root[data-theme="dark"] {', "  color-scheme: dark;", *declarations("dark"), "}", ""]
    # A data-cand-style element takes that style's palette in the current
    # theme; data-cand-tone pins one theme (thumbnails of the other theme).
    for style in tokens["candidate"]:
        lines += [f'[data-cand-style="{style}"] {{', *candidate(style, "light"), "}", "",
                  f':root[data-theme="dark"] [data-cand-style="{style}"] {{', *candidate(style, "dark"), "}", ""]
    for style in tokens["candidate"]:
        for mode in ("light", "dark"):
            lines += [f':root [data-cand-style="{style}"][data-cand-tone="{mode}"] {{',
                      *candidate(style, mode), "}", ""]
    return "\n".join(lines)


def validate(tokens: dict) -> None:
    for mode in ("light", "dark"):
        if tokens["color"][mode].keys() != tokens["color"]["light"].keys() or \
           tokens["shadow"][mode].keys() != tokens["shadow"]["light"].keys():
            raise SystemExit(f"{mode} tokens must define the same keys as light")
    if DEFAULT_STYLE not in tokens["candidate"]:
        raise SystemExit(f"the candidate tokens must define the default style {DEFAULT_STYLE}")
    # Every candidate style fills the same palette, in both themes.
    reference = tokens["candidate"][DEFAULT_STYLE]["light"].keys()
    for style, modes in tokens["candidate"].items():
        for mode in ("light", "dark"):
            if modes[mode].keys() != reference:
                raise SystemExit(f"candidate {style}/{mode} must define the same keys as {DEFAULT_STYLE}/light")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--tokens", type=Path, default=TOKENS)
    parser.add_argument("--header", type=Path)
    parser.add_argument("--css", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    tokens = json.loads(args.tokens.read_text(encoding="utf-8"))
    validate(tokens)
    if args.header:
        args.header.parent.mkdir(parents=True, exist_ok=True)
        args.header.write_text(header(tokens), encoding="utf-8", newline="\n")
    if args.css:
        expected = css(tokens)
        if args.check:
            actual = args.css.read_text(encoding="utf-8") if args.css.exists() else ""
            if actual != expected:
                print(f"{args.css} is out of date; run tools/generate_design_tokens.py --css {args.css}",
                      file=sys.stderr)
                return 1
        else:
            args.css.write_text(expected, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
